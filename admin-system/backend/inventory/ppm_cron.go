// HandleGetEquipmentHealth returns health gauges and meter stats for all machines
func HandleGetEquipmentHealth(c *gin.Context) {
	_, indicators := RunPredictiveMaintenanceCheck()
	c.JSON(http.StatusOK, gin.H{
		"status":     "success",
		"timestamp":  time.Now().Format(time.RFC3339),
		"indicators": indicators,
	})
}

// HandleGetMaintenanceTickets lists open and historical maintenance tickets
func HandleGetMaintenanceTickets(c *gin.Context) {
	ppmStoreMutex.RLock()
	defer ppmStoreMutex.RUnlock()

	list := make([]MaintenanceTicket, 0, len(maintenanceTicketsStore))
	for _, t := range maintenanceTicketsStore {
		list = append(list, t)
	}

	c.JSON(http.StatusOK, gin.H{
		"status":  "success",
		"tickets": list,
	})
}

// HandleTriggerPPMCheck runs an on-demand predictive maintenance inspection
func HandleTriggerPPMCheck(c *gin.Context) {
	newTickets, indicators := RunPredictiveMaintenanceCheck()
	c.JSON(http.StatusOK, gin.H{
		"status":      "success",
		"message":     fmt.Sprintf("PPM Inspection completed. %d new maintenance tickets generated.", len(newTickets)),
		"new_tickets": newTickets,
		"indicators":  indicators,
	})
}

// HandleResolveMaintenanceTicket resolves a ticket and resets the serviced meter
func HandleResolveMaintenanceTicket(c *gin.Context) {
	ticketID := c.Param("id")

	ppmStoreMutex.Lock()
	ticket, exists := maintenanceTicketsStore[ticketID]
	if !exists {
		ppmStoreMutex.Unlock()
		c.JSON(http.StatusNotFound, gin.H{"error": "Maintenance ticket not found"})
		return
	}

	now := time.Now()
	ticket.Status = "RESOLVED"
	ticket.ResolvedAt = &now
	maintenanceTicketsStore[ticketID] = ticket
	ppmStoreMutex.Unlock()

	// Reset equipment last_serviced_meter
	storeMutex.Lock()
	if eq, eqExists := equipmentStore[ticket.EquipmentID]; eqExists {
		if eq.TechnicalSpecs == nil {
			eq.TechnicalSpecs = make(map[string]interface{})
		}
		curMeter := 0
		if cm, ok := eq.TechnicalSpecs["current_meter"].(float64); ok {
			curMeter = int(cm)
		} else if cmInt, ok := eq.TechnicalSpecs["current_meter"].(int); ok {
			curMeter = cmInt
		}
		eq.TechnicalSpecs["last_serviced_meter"] = curMeter
		equipmentStore[ticket.EquipmentID] = eq
	}
	storeMutex.Unlock()

	if db.DB != nil {
		_, _ = db.DB.Exec(`UPDATE maintenance_tickets SET status = 'RESOLVED', resolved_at = NOW() WHERE id = $1`, ticketID)
	}

	c.JSON(http.StatusOK, gin.H{
		"status":  "success",
		"message": "Maintenance ticket resolved and last_serviced_meter reset to current meter",
		"ticket":  ticket,
	})
}

// StartPPMDailyCron runs the predictive maintenance check in the background daily
func StartPPMDailyCron() {
	go func() {
		ticker := time.NewTicker(24 * time.Hour)
		defer ticker.Stop()

		// Run immediate initial check on startup
		log.Println("[PPM CRON] Running startup Predictive Maintenance check...")
		RunPredictiveMaintenanceCheck()

		for range ticker.C {
			log.Println("[PPM CRON] Running scheduled daily Predictive Maintenance check...")
			RunPredictiveMaintenanceCheck()
		}
	}()
}
